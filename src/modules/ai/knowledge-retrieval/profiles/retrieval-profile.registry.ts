export function resolveRetrievalProfile(params: {
  taskType: AiDbTaskType;
  profileId?: string;
}): RetrievalProfile {
  if (params.profileId && RETRIEVAL_PROFILES[params.profileId]) {
    return RETRIEVAL_PROFILES[params.profileId]!;
  }
  const id = TASK_DEFAULT_PROFILE[params.taskType] ?? 'farmer-chat-v1';
  return RETRIEVAL_PROFILES[id]!;
}

export function normalizeRetrievalQuery(query: string): string {
  return query.trim().replace(/\s+/g, ' ');
}

export function domainPriorityBoost(
  contentType: AiKnowledgeContentType,
  domainPriority: AiKnowledgeContentType[],
): number {
  const index = domainPriority.indexOf(contentType);
  if (index < 0) return 0.5;
  return 1 - index / Math.max(domainPriority.length, 1);
}
